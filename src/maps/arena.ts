import type { GameMap, Point } from '@sim/index';

/**
 * Единственная карта v1: симметричная арена на две Стороны.
 *
 * Симметрия здесь не украшение, а условие измеримости: Автопрогон должен
 * мерить качество Правил, а не выгодность стартовой позиции. Поэтому вся
 * карта зеркальна относительно вертикальной оси: Юниты сходят с Дорог
 * и встречаются у Цитаделей с Юнитами других Дорог (ADR-0004), и
 * симметрии каждой Дороги по отдельности мало. Обходные Дороги вдобавок
 * зеркальны относительно горизонтальной оси, что делает их длины равными
 * с точностью до бита.
 *
 * Координаты собственные, не пиксельные: рендер вписывает поле в окно.
 */

const WIDTH = 1200;
const HEIGHT = 840;
/** Высота, на которой стоят обе Цитадели. */
const CITADEL_Y = 420;
/** Высота прямого участка обходных Дорог. */
const DETOUR_Y = 80;

const p = (x: number, y: number): Point => ({ x, y });
/** Отражение точки по горизонтальной оси поля: обходные Дороги зеркальны. */
const flip = (point: Point): Point => p(point.x, HEIGHT - point.y);

const A = p(150, CITADEL_Y);
const B = p(1050, CITADEL_Y);

/**
 * Обходной маршрут: подъём от Цитадели A, прямой участок вдоль края,
 * спуск к Цитадели B. Три сегмента — два излома, поэтому на экране это
 * читается как отдельная дорога, а не как половина овала.
 *
 * Из Цитадели маршрут выходит под углом, а не строго вверх: иначе обе
 * обходные Дороги касаются друг друга у Цитадели и сливаются в глазах
 * в один замкнутый контур вместо развилки из трёх маршрутов.
 */
const NORTH: readonly Point[] = [
  A,
  p(210, 300), p(250, DETOUR_Y), p(380, DETOUR_Y),
  p(520, DETOUR_Y), p(680, DETOUR_Y), p(820, DETOUR_Y),
  p(950, DETOUR_Y), p(990, 300), B,
];

/** Насколько Обелиск отстоит от прямого участка Дороги к центру поля. */
const OBELISK_OFFSET = 60;
const OBELISK_NORTH = p(WIDTH / 2, DETOUR_Y + OBELISK_OFFSET);

export const arena: GameMap = {
  size: { width: WIDTH, height: HEIGHT },

  citadels: [
    { side: 'A', at: A },
    { side: 'B', at: B },
  ],

  roads: [
    {
      id: 'short',
      from: 'A',
      to: 'B',
      // Один сегмент: короткий маршрут в лоб. Прямой: изогнутый буквой S
      // был бы симметричен лишь поворотом, а не отражением, как вся карта.
      points: [A, p(450, CITADEL_Y), p(750, CITADEL_Y), B],
    },
    { id: 'north', from: 'A', to: 'B', points: NORTH },
    { id: 'south', from: 'A', to: 'B', points: NORTH.map(flip) },
  ],

  // По Обелиску на обходную Дорогу (спека 0003): в середине прямого
  // участка, в стороне от Дороги к центру поля. Оба стоят на вертикальной
  // оси, поэтому до них одинаково далеко обеим Сторонам.
  obelisks: [
    { id: 'north', at: OBELISK_NORTH },
    { id: 'south', at: flip(OBELISK_NORTH) },
  ],
};
