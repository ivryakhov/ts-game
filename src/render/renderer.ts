/**
 * Граница отрисовки. Рендер получает только время для анимаций и ничего
 * не может изменить в мире (ADR-0001).
 *
 * Интерфейс намеренно узкий: заменить Canvas на PixiJS означает написать
 * другую реализацию двух методов, не трогая ни симуляцию, ни главный цикл.
 *
 * Снимок состояния появится здесь в тикете 03 вместе с первыми Юнитами.
 * Сочинять его раньше времени нельзя: состояние мира рождается только
 * внутри матча.
 */
export interface Renderer {
  /** Новый размер области в css-пикселях. */
  resize(width: number, height: number): void;
  draw(frame: Frame): void;
}

export interface Frame {
  /**
   * Миллисекунды с начала работы страницы — только для анимаций.
   * На симуляцию не влияет и в неё не попадает.
   */
  readonly elapsedMs: number;
}
