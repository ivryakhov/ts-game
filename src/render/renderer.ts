import type { WorldSnapshot } from '@sim/index';

/**
 * Граница отрисовки. Рендер получает два снимка мира и долю пути между
 * ними — и ничего не может изменить, потому что снимки неизменяемы
 * (ADR-0001).
 *
 * Два снимка нужны для сглаживания: симуляция идёт двадцать раз в секунду,
 * экран обновляется в три раза чаще, и без интерполяции Юниты дёргались бы.
 *
 * Интерфейс намеренно узкий: заменить Canvas на PixiJS означает написать
 * другую реализацию двух методов, не трогая ни симуляцию, ни главный цикл.
 */
export interface Renderer {
  /** Новый размер области в css-пикселях. */
  resize(width: number, height: number): void;
  draw(frame: Frame): void;
}

export interface Frame {
  readonly previous: WorldSnapshot;
  readonly current: WorldSnapshot;
  /** Доля пути от предыдущего Тика к текущему, от 0 до 1. */
  readonly alpha: number;
  /**
   * Время матча в миллисекундах — только для анимаций. Отсчитывается
   * от Тиков, а не от системных часов, поэтому свечение на Дорогах
   * замирает на паузе и ускоряется вместе с симуляцией.
   */
  readonly matchMs: number;
}
