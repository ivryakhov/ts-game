import type { SideId, UnitId, WorldSnapshot } from '@sim/index';

/**
 * Граница отрисовки. Рендер получает два снимка мира и долю пути между
 * ними — и ничего не может изменить, потому что снимки неизменяемы
 * (ADR-0001).
 *
 * Два снимка нужны для сглаживания: симуляция идёт двадцать раз в секунду,
 * экран обновляется в три раза чаще, и без интерполяции Юниты дёргались бы.
 *
 * Интерфейс намеренно узкий: заменить Canvas на PixiJS означает написать
 * другую реализацию двух методов, не трогая ни симуляцию, ни главный цикл.
 */
export interface Renderer {
  /** Новый размер области в css-пикселях. */
  resize(width: number, height: number): void;
  draw(frame: Frame): void;
  /**
   * Какая Дорога лежит под точкой экрана. Обратное преобразование живёт
   * здесь же, где прямое: иначе ввод и отрисовка разъедутся в том, где
   * проходит Дорога.
   */
  roadAt(x: number, y: number): string | null;
  /** Какой Юнит нарисован под точкой экрана в последнем кадре. */
  unitAt(x: number, y: number): UnitId | null;
}

export interface Frame {
  readonly previous: WorldSnapshot;
  readonly current: WorldSnapshot;
  /**
   * Кто погиб с прошлого кадра. Исчезнуть из мира Юнит может двояко —
   * погибнув или дойдя до чужой Цитадели, — и показ обязан различать
   * эти случаи.
   */
  readonly deaths: ReadonlySet<UnitId>;
  /** Доля пути от предыдущего Тика к текущему, от 0 до 1. */
  readonly alpha: number;
  /**
   * Время матча в миллисекундах — для анимаций мира. Отсчитывается
   * от Тиков, а не от системных часов, поэтому свечение на Дорогах
   * замирает на паузе и ускоряется вместе с симуляцией.
   */
  readonly matchMs: number;
  /**
   * Время по часам — для сигналов игроку. Вспышка тревоги обязана быть
   * видна человеку, поэтому её длительность не должна сжиматься при
   * ускоренном воспроизведении.
   */
  readonly realMs: number;
  /** Чьи Цитадели получили урон с прошлого кадра. */
  readonly citadelHits: ReadonlySet<SideId>;
  /** Дорога под курсором — её подсвечивают как выбранную. */
  readonly highlightedRoad: string | null;
  /** Юнит, которого игрок выделил, чтобы разобрать его Поведение. */
  readonly selectedUnit: UnitId | null;
}
