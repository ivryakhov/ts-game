/**
 * Числовые характеристики игры. Собраны в одном месте, потому что их
 * предстоит крутить сотнями итераций: панель правки на лету и Автопрогон
 * из тикетов спеки 0003 будут читать именно отсюда.
 */

/** Частота симуляции. Длительность Тика неизменна; скорость меняет только их число за кадр. */
export const TICKS_PER_SECOND = 20;

/** Условных единиц карты в секунду. */
const BASE_SPEED_PER_SECOND = 120;
/** Урона в секунду. */
const BASE_DAMAGE_PER_SECOND = 15;

/** Цена Юнита. Вынесена отдельно, потому что её показывает панель. */
export const UNIT_COST = 20;

export const UNIT_STATS = {
  maxHp: 50,
  cost: UNIT_COST,
  /** Условных единиц карты за один Тик. */
  speedPerTick: BASE_SPEED_PER_SECOND / TICKS_PER_SECOND,
  /** Урона за один Тик. */
  damagePerTick: BASE_DAMAGE_PER_SECOND / TICKS_PER_SECOND,
} as const;

/** Экономика Стороны. */
export const ECONOMY = {
  /** С чего начинается матч. */
  startingEther: 100,
  /** Пассивный доход в секунду. */
  incomePerSecond: 5,
} as const;

export const CITADEL_STATS = {
  maxHp: 1000,
  /**
   * Какая доля урона Юнита доходит до Цитадели. Меньше единицы намеренно:
   * иначе всё решает одна волна, добежавшая мимо Стычек, и удерживать
   * Дорогу оказывается бессмысленно.
   */
  damageShare: 0.5,
} as const;

export const SKIRMISH = {
  /** На каком расстоянии вдоль Дороги враги замечают друг друга и встают. */
  engageRange: 26,
  /**
   * Сколько Юнитов с каждой Стороны бьётся одновременно. Концепт говорит
   * о восьми; пока тип Юнита один, взято три — чтобы очередь была видна
   * на глаз и проверяема. Число уточнится на плейтестах.
   */
  limit: 3,
  /** Насколько плотно Юниты встают в очередь за теми, кто уже в Стычке. */
  spacing: 20,
} as const;
