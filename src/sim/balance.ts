/**
 * Числовые характеристики игры. Собраны в одном месте, потому что их
 * предстоит крутить сотнями итераций: панель правки на лету и Автопрогон
 * из тикетов спеки 0003 будут читать именно отсюда.
 */

/** Частота симуляции. Длительность Тика неизменна; скорость меняет только их число за кадр. */
export const TICKS_PER_SECOND = 20;

/** Условных единиц карты в секунду. */
const BASE_SPEED_PER_SECOND = 80;
/** Урона в секунду. */
const BASE_DAMAGE_PER_SECOND = 15;

const perTick = (perSecond: number): number => perSecond / TICKS_PER_SECOND;

/** Типы Юнитов. Поддержка вырезана из v1 — см. docs/v1-plan.md. */
export type UnitKind = 'scout' | 'tank' | 'ranger';

export const UNIT_KINDS: readonly UnitKind[] = ['scout', 'tank', 'ranger'];

export interface UnitStats {
  readonly maxHp: number;
  readonly cost: number;
  /**
   * Бьёт ли Юнит издали. Дальний не лезет в свалку и не занимает место
   * вплотную к врагу — это его свойство, а не следствие того, что число
   * дальности вышло больше ближнего порога.
   */
  readonly ranged: boolean;
  /** Условных единиц карты за один Тик. */
  readonly speedPerTick: number;
  /** Урона за один Тик. */
  readonly damagePerTick: number;
  /**
   * Дальность удара по прямой, от центра до центра. У ближних это
   * расстояние, на котором два тела соприкасаются, — они бьют только
   * вплотную. Стрелок бьёт издали, поверх своих.
   */
  readonly range: number;
  /**
   * На каком расстоянии по прямой Юнит замечает врага и готов сойти
   * с Дороги, чтобы его бить. Это и есть «враг в радиусе» для Правил.
   */
  readonly sight: number;
}

/**
 * Радиус тела Юнита. Тела не налезают друг на друга: Юнит не проходит
 * сквозь других, а ближний бьёт только того, к кому подошёл вплотную.
 */
export const BODY_RADIUS = 12;

/** Зазор между поверхностями, при котором ближний уже достаёт врага. */
export const MELEE_GAP = 4;

/** Дальность ближнего удара по Юниту: расстояние между центрами при касании. */
export const MELEE_RANGE = BODY_RADIUS * 2 + MELEE_GAP;

/**
 * Что значит «союзник рядом» для Условия Правил: не дальше этого по
 * прямой. Идущая Колонна растягивается до тридцати единиц на Юнита,
 * и так в «рядом» попадают трое, идущих в затылок друг другу.
 */
export const NEARBY_RANGE = 100;

/** Радиус тела Цитадели: враг не заходит внутрь, а встаёт вокруг неё. */
export const CITADEL_RADIUS = 44;

